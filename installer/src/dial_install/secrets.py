"""The single customer-owned Secrets Manager secret.

The installer only READS it. `init` generates a ready-to-upload JSON file; the
customer creates the secret and gives us its ARN. Keys are never regenerated by
the installer, so stored data stays readable across upgrades.
"""

from __future__ import annotations

import base64
import json
import os
import secrets as _secrets
import string
from dataclasses import dataclass

from .cloud import Cloud
from .errors import InstallerError

PLACEHOLDER_MARKERS = ("TODO", "CHANGEME", "REPLACE")


@dataclass(frozen=True)
class SecretKey:
    name: str
    kind: str          # how `init` generates it
    purpose: str


def _b64(nbytes: int) -> str:
    return base64.b64encode(os.urandom(nbytes)).decode()


def _hex(nbytes: int) -> str:
    return os.urandom(nbytes).hex()


def _password12() -> str:
    alphabet = string.ascii_letters + string.digits
    while True:
        value = "".join(_secrets.choice(alphabet) for _ in range(12))
        if any(c.islower() for c in value) and any(c.isupper() for c in value) and any(c.isdigit() for c in value):
            return value


# kind -> generator. Sizes follow what DIAL expects for each secret.
_GENERATORS = {
    "b64_48": lambda: _b64(48),
    "b64_64": lambda: _b64(64),
    "b64_32": lambda: _b64(32),
    "hex16": lambda: _hex(16),
    "hex24": lambda: _hex(24),
    "hex32": lambda: _hex(32),
    "db_password": lambda: _db_password(),
    "grafana": _password12,
}


def _db_password() -> str:
    """Aurora master password: letters and digits only (no characters RDS or URLs reject)."""
    alphabet = string.ascii_letters + string.digits
    while True:
        value = "".join(_secrets.choice(alphabet) for _ in range(24))
        if any(c.islower() for c in value) and any(c.isupper() for c in value) and any(c.isdigit() for c in value):
            return value


REQUIRED_KEYS: tuple[SecretKey, ...] = (
    SecretKey("db_master_password", "db_password", "Aurora master password and Admin database login"),
    SecretKey("dial_api_key", "b64_48", "Internal API key used by QuickApps"),
    SecretKey("core_admin_api_key", "b64_48", "Core admin API key"),
    SecretKey("core_encryption_secret", "hex16", "Core data encryption secret (never change after first install)"),
    SecretKey("core_encryption_key", "hex16", "Core data encryption key (never change after first install)"),
    SecretKey("cognito_logging_salt", "hex32", "Salt for hashing user identifiers in logs"),
    SecretKey("admin_nextauth_secret", "b64_64", "Admin UI session secret"),
    SecretKey("superset_admin_password", "hex24", "Superset admin password"),
    SecretKey("superset_secret_key", "hex32", "Superset secret key"),
    SecretKey("superset_dashboard_artifact_signing_secret", "hex32", "Superset dashboard signing secret"),
    SecretKey("dashboards_signing_secret", "hex32", "Chat dashboards signing secret (min 32 chars)"),
    SecretKey("influxdb_password", "b64_32", "InfluxDB admin password"),
    SecretKey("influxdb_token", "hex32", "InfluxDB API token"),
    SecretKey("grafana_admin_password", "grafana", "Grafana admin password (min 12 chars)"),
)


def generate() -> dict[str, str]:
    """Return a complete, random secret document for `init`."""
    return {key.name: _GENERATORS[key.kind]() for key in REQUIRED_KEYS}


def create_command(name: str, region: str, file_name: str = "dial-secrets.json") -> str:
    return (
        f"aws secretsmanager create-secret --name dial/{name} "
        f"--secret-string file://{file_name} --region {region}"
    )


def fetch(cloud: Cloud, arn: str) -> dict[str, str]:
    """Read and parse the secret. Raises InstallerError with a fix hint."""
    result = cloud.aws("secretsmanager", "get-secret-value", "--secret-id", arn,
                       "--query", "SecretString", "--output", "text", check=False)
    if result.returncode != 0:
        raise InstallerError(
            f"Cannot read the secret {arn}",
            "Check the ARN, the region, and that your AWS user may call secretsmanager:GetSecretValue on it.\n"
            + (result.stderr.strip() if result.stderr else ""),
        )
    try:
        data = json.loads(result.stdout)
    except json.JSONDecodeError:
        raise InstallerError(
            "The secret value is not JSON.",
            "It must be the JSON document generated by `dial-install init` (dial-secrets.json).",
        ) from None
    if not isinstance(data, dict):
        raise InstallerError("The secret value must be a JSON object of key/value pairs.")
    return {str(k): str(v) for k, v in data.items()}


def audit(data: dict[str, str]) -> dict[str, str]:
    """Map each required key to 'present', 'missing' or 'placeholder'."""
    status = {}
    for key in REQUIRED_KEYS:
        value = data.get(key.name, "")
        if not value:
            status[key.name] = "missing"
        elif any(marker in value.upper() for marker in PLACEHOLDER_MARKERS):
            status[key.name] = "placeholder"
        else:
            status[key.name] = "present"
    if len(data.get("dashboards_signing_secret", "")) < 32 and status["dashboards_signing_secret"] == "present":
        status["dashboards_signing_secret"] = "too short (need 32+ characters)"
    if len(data.get("grafana_admin_password", "")) < 12 and status["grafana_admin_password"] == "present":
        status["grafana_admin_password"] = "too short (need 12+ characters)"
    return status
